
namespace Magnetar.Core
{
    public struct Vector4D
    {
        public float x;
        public float y;
        public float z;
        public float w;

        public Vector4D(float x, float y, float z, float w)
        {
            this.x = x;
            this.y = y;
            this.z = z;
            this.w = w;
        }
    }
}